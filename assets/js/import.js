/* import.js — take a puzzle off someone else's screen and make it one of ours.

   Pure logic: no DOM, no board, no buttons. trainer.js owns the typing surface
   and calls in here to ask whether what was typed is a real puzzle, and what
   kind. Everything a bank entry carries is derived rather than asked for — the
   solution comes from the solver, the technique tags from the coach's own
   detectors — so the only thing a person has to supply is the printed digits.

   The validation is the point of the module, not its chore. A single misread
   digit yields a coach that talks confident nonsense for twenty moves, and the
   solver can tell you the grid is wrong before you have wasted any of that. */
(function (root) {
  'use strict';
  const C = root.SudokuCore, T = root.SudokuTech;

  const ADV = ['xwing', 'skyscraper', 'swordfish', 'xy_wing'];
  const SUBSET = ['naked_2', 'hidden_2', 'naked_3', 'hidden_3'];
  /* The detectors' names against the bank's. bank.js was generated by the
     Python engine and uses the shorter ones; an imported puzzle is a bank entry
     like any other, so it has to speak the bank's vocabulary. */
  const TAG = {
    naked_pair: 'naked_2', hidden_pair: 'hidden_2',
    naked_triple: 'naked_3', hidden_triple: 'hidden_3'
  };
  /* Advanced by the coach's ranking: 7 is the X-Wing. Below it are the singles,
     the locked candidates and the subsets — the moves you were already making
     before you got stuck. */
  const ADV_RANK = 7;

  function cellList(cells, cap) {
    const names = cells.map(C.cellName);
    if (names.length <= cap) return names.join(', ');
    return names.slice(0, cap).join(', ') + ' and ' + (names.length - cap) + ' more';
  }

  /* The characters a grid is made of: the nine digits, and the several things
     people write for an empty square. Everything else — pipes, plus signs, the
     line breaks a copied grid arrives wrapped in — is furniture. */
  const BLANKS = '0.-_*?';
  function gridChar(ch) { return (ch >= '1' && ch <= '9') || BLANKS.indexOf(ch) >= 0; }

  /* Anything that is not a digit is a blank. Grids get pasted with dots,
     dashes, pipes and line breaks in them, and nine digits typed on a phone
     arrive with whatever the keyboard felt like adding. */
  function normalise(text) {
    let out = '';
    const s = String(text || '');
    for (let k = 0; k < s.length; k++) {
      const ch = s[k];
      if (!gridChar(ch)) continue;
      out += (ch >= '1' && ch <= '9') ? ch : '0';
    }
    return out;
  }

  /* ---------------- laying it out ----------------
     The same 81 characters, shaped like the thing they describe: nine to a
     line, and grouped in threes so the boxes are visible. Checking a
     transcription against a printed grid means reading them side by side, and
     an unbroken run of eighty-one characters cannot be read side by side with
     anything — you lose your place on the fourth row and start again.

     Blanks are left as the person wrote them rather than folded to 0. Someone
     typing dots is doing it because dots disappear and digits do not, which is
     the whole reason to prefer them, and normalise() takes either.

     The gaps go in both directions: a space after every third character and a
     blank line after every third row, so the nine boxes are visible as nine
     boxes. That is what you are checking against — a printed grid is read box
     by box, not row by row.

     `sep` returns what goes IN FRONT of the n-th character, and gridCaret walks
     the same function rather than reimplementing the arithmetic, because the
     two have to agree exactly or the caret drifts a little further from the
     cursor with every row. */
  function sep(n) {
    if (!n) return '';
    if (n % 27 === 0) return '\n\n';
    if (n % 9 === 0) return '\n';
    if (n % 3 === 0) return ' ';
    return '';
  }

  function gridify(text) {
    const s = String(text || '');
    let out = '', n = 0;
    for (let k = 0; k < s.length; k++) {
      const ch = s[k];
      if (!gridChar(ch)) continue;
      out += sep(n) + ch;
      n++;
    }
    return out;
  }

  /* Where the caret belongs after a relayout: the spot that still has `n` grid
     characters in front of it. */
  function gridCaret(n, len) {
    let pos = 0;
    for (let i = 0; i < n; i++) pos += sep(i).length + 1;
    return Math.min(pos, len);
  }

  /* Same digit twice in a unit. Cheap, and it catches the commonest slip
     before the solver has to. */
  function conflicts(grid) {
    const bad = new Set();
    C.UNITS.forEach(u => {
      const where = new Map();
      u.forEach(i => {
        const v = grid[i];
        if (!v) return;
        if (!where.has(v)) where.set(v, []);
        where.get(v).push(i);
      });
      where.forEach(cells => { if (cells.length > 1) cells.forEach(i => bad.add(i)); });
    });
    return [...bad].sort((a, b) => a - b);
  }

  /* Both ways a transcription goes wrong are a single-cell change: a digit read
     as the wrong one, or a printed digit skipped. So the diagnostic is to
     enumerate the changes of that shape and keep the ones that turn the grid
     into a real puzzle — exactly one solution. What comes back is usually a
     handful of squares rather than one, which is still the difference between
     re-reading six squares and re-reading eighty-one.

     `mode` is 'edit' (change or clear a digit that is in) or 'add' (fill a
     square that is empty). Every square of that kind is tried, which is the
     part worth not being clever about: scoping the search for a missing given
     to the squares two solutions disagree on looks sound and is not — when
     more than two solutions exist, the two the solver happens to return can
     agree on the square you actually skipped, and the search then confidently
     names a different one.

     Costs one solver run per candidate, up to `budget` of them — a second on a
     laptop, a few on a phone, behind a button press, and worth it.

     Deliberately NOT "which given, removed, lets it solve": on a contradictory
     grid that is true of nearly every given, since dropping any constraint lets
     the wrong digit find a home. It names two dozen squares and means nothing. */
  function repairs(grid, mode, budget) {
    const out = [];
    let spent = 0;
    for (let i = 0; i < 81; i++) {
      if (mode === 'edit' ? !grid[i] : grid[i]) continue;
      for (let d = (mode === 'edit' ? 0 : 1); d <= 9; d++) {
        if (grid[i] === d) continue;
        const g = grid.slice();
        g[i] = d;
        if (d && conflicts(g).length) continue;
        if (spent++ > (budget || 1500)) return out;
        if (C.solve(g, 2).length === 1) out.push({ cell: i, digit: d });
      }
    }
    return out;
  }

  /* One repair is an answer; several are a shortlist. Worded as a description
     of what was found rather than a promise that the mistake is inside it: the
     search is capped, and a list that claims to be exhaustive should be. */
  function repairLine(reps) {
    if (reps.length === 1) {
      const r = reps[0];
      return ' One change makes it a real puzzle: <b>' + C.cellName(r.cell) + '</b> has to be <b>' +
             (r.digit ? r.digit : 'empty') + '</b>.';
    }
    const cells = [...new Set(reps.map(r => r.cell))];
    if (!cells.length) return '';
    return ' These squares are each a single change away from a real puzzle, and are marked on ' +
           'the board: ' + cellList(cells, 6) + '. Re-read those against the printed grid.';
  }

  /* Play the position with the coach's own detectors, cheapest move first — the
     same loop the drill builder runs. `stopRank` ends it before the first move
     at that rank or above, which is how "catch me up to where it gets hard" is
     expressed. Pass 0 to play it out as far as the nine patterns reach.

     Deliberately the coach's detectors and not the backtracking solver: the
     question being asked is what THIS site can see in the position, and a
     search that always wins would answer a different one. */
  function walk(grid, notes, stopRank) {
    const g = grid.slice();
    const n = notes ? notes.map(s => new Set(s)) : C.baseCandidates(g);
    const played = [];
    const seen = new Map();
    let stopped = null;
    for (let step = 0; step < 500; step++) {
      const { findings } = T.findAll(g, n);
      if (!findings.length) break;
      const f = findings[0];
      if (stopRank && f.rank >= stopRank) { stopped = f; break; }
      if (seen.has(f.id)) played[seen.get(f.id)][1]++;
      else { seen.set(f.id, played.length); played.push([f.id, 1]); }
      if (f.placement) {
        g[f.placement.cell] = f.placement.digit;
        n[f.placement.cell] = new Set();
        C.PEERS[f.placement.cell].forEach(x => n[x].delete(f.placement.digit));
      } else f.elims.forEach(e => n[e.cell].delete(e.digit));
    }
    return { grid: g, notes: n, played, stopped, filled: g.filter(v => v).length };
  }

  /* What the technique walk says about a puzzle, in the words the trainer wants
     to print the moment an import lands. Three outcomes worth telling apart —
     and the middle one is the useful one for someone who is stuck: if the nine
     patterns crack it without an advanced move, the thing they are missing is
     probably a digit they got wrong, not a pattern they have not learned. */
  function verdict(puzzle, w, names) {
    const needs = puzzle.adv.map(x => names[x]).join(' + ');
    if (w.filled === 81) {
      return puzzle.adv.length
        ? 'Read clean, and the nine patterns take it all the way. Past the singles it needs ' +
          needs + '.'
        : 'Read clean — and it falls to singles, locked candidates and subsets alone, with ' +
          'nothing advanced needed. If you are stuck on it, look first for an entry of yours ' +
          'that is wrong rather than a pattern you have missed.';
    }
    return 'Read clean, and it is a real puzzle — but the nine patterns here stall at ' +
      w.filled + ' of 81 squares' + (puzzle.adv.length ? ', after ' + needs : '') +
      '. Past that it wants something this site does not teach. Import it anyway if you ' +
      'want the coach for the part it can see.';
  }

  /* The whole import in one call. Returns either a bank-shaped puzzle or a
     refusal that says which squares to look at again. */
  function analyze(text, names) {
    names = names || {};
    const p = normalise(text);
    if (!p.length) {
      return { ok: false, code: 'empty', cells: [],
        message: 'Nothing read yet. Tap a square, then a number, for each digit the puzzle prints.' };
    }
    if (p.length !== 81) {
      return { ok: false, code: 'length', cells: [],
        message: p.length + ' characters read and a grid is 81. Blanks count: use 0 or a dot for ' +
                 'every empty square.' };
    }
    const grid = C.parse(p);
    const givens = grid.filter(v => v).length;
    if (!givens) {
      return { ok: false, code: 'empty', cells: [],
        message: 'That grid is empty. Enter the digits the puzzle starts with.' };
    }

    const clash = conflicts(grid);
    if (clash.length) {
      return { ok: false, code: 'conflict', cells: clash,
        message: 'Two of the same digit share a row, column or box — ' + cellList(clash, 6) +
                 ', marked on the board. One of them is misread.' };
    }

    const sols = C.solve(grid, 2);
    if (!sols.length) {
      const reps = repairs(grid, 'edit');
      return { ok: false, code: 'unsolvable', cells: [...new Set(reps.map(r => r.cell))],
        message: 'No arrangement completes this grid, so one of the digits is misread.' +
          (reps.length ? repairLine(reps)
                       : ' No single change fixes it either, so more than one is wrong — ' +
                         'worth clearing the grid and reading it again.') };
    }
    if (sols.length > 1) {
      const differ = [];
      for (let i = 0; i < 81; i++) if (sols[0][i] !== sols[1][i]) differ.push(i);
      /* A skipped given is the usual cause and the cheaper search, so it goes
         first; a digit misread into a grid that is merely ambiguous rather than
         impossible is the other way it happens. */
      let reps = repairs(grid, 'add');
      if (!reps.length) reps = repairs(grid, 'edit');
      return { ok: false, code: 'multiple',
        cells: reps.length ? [...new Set(reps.map(r => r.cell))] : differ,
        message: 'This grid has more than one solution, which a printed puzzle never does — ' +
          'so a given is missing. Only ' + givens +
          ' are in' + (givens < 17 ? ', and no sudoku is unique below 17' : '') + '.' +
          (reps.length ? repairLine(reps)
                       : ' The two solutions disagree on ' + differ.length + ' squares, marked ' +
                         'on the board; the one you skipped is among them.') };
    }

    const w = walk(grid, null, 0);
    const t = [...new Set(w.played.map(x => TAG[x[0]] || x[0]))].sort();
    const adv = ADV.filter(x => t.includes(x));
    const puzzle = {
      p, s: sols[0].join(''), t, adv, givens,
      level: adv.length ? 'advanced' : (t.some(x => SUBSET.includes(x)) ? 'intermediate' : 'basic'),
      imported: Date.now()
    };
    return { ok: true, code: 'ok', cells: [], puzzle, walk: w,
             message: verdict(puzzle, w, names) };
  }

  /* ---------------- keeping them ----------------
     Only the puzzle, not the position: a definition is 81 characters and
     survives anything, while a half-played board is a much bigger promise than
     this needs to make. Restart already exists for getting back to the start.

     localStorage throws outright in some privacy modes, and a puzzle you cannot
     save is not a reason to take the trainer down — same handling as pwa.js,
     and the same prefix, because storage belongs to the whole github.io
     account rather than to this project's path. */
  const KEY = 'ast:imports';
  const LIMIT = 8;
  function memory(value) {
    try {
      if (value === undefined) return window.localStorage.getItem(KEY);
      window.localStorage.setItem(KEY, value);
    } catch (e) { /* no memory available; imports last as long as the tab */ }
    return null;
  }
  function saved() {
    try {
      const raw = memory();
      const a = raw ? JSON.parse(raw) : [];
      return Array.isArray(a) ? a.filter(x => x && typeof x.p === 'string' && x.p.length === 81) : [];
    } catch (e) { return []; }
  }
  function save(puzzle) {
    const all = saved().filter(x => x.p !== puzzle.p);
    all.unshift(puzzle);
    memory(JSON.stringify(all.slice(0, LIMIT)));
    return all.slice(0, LIMIT);
  }
  function forget(p) {
    const all = saved().filter(x => x.p !== p);
    memory(JSON.stringify(all));
    return all;
  }

  /* ---------------- links ----------------
     An imported puzzle is 81 characters, so it fits in the URL and a link is
     the cheapest way to move one between the phone and the desk, or to keep it
     somewhere this site cannot reach. */
  function fromHash(hash) {
    const m = /[#&]p=([^&]+)/.exec(hash === undefined ? window.location.hash : hash);
    if (!m) return null;
    const p = normalise(decodeURIComponent(m[1]));
    return p.length === 81 ? p : null;
  }
  function setHash(p) {
    try { window.history.replaceState(null, '', '#p=' + p); } catch (e) { /* file:// */ }
  }
  function clearHash() {
    try { window.history.replaceState(null, '', window.location.pathname + window.location.search); }
    catch (e) { /* file:// */ }
  }

  root.SudokuImport = {
    ADV_RANK, normalise, gridChar, gridify, gridCaret, conflicts, repairs, walk, analyze,
    saved, save, forget, fromHash, setHash, clearHash
  };
})(typeof window !== 'undefined' ? window : globalThis);
